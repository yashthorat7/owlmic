fn unpack_master() -> [u8; 65536] {
    let mut grid = [0u8; 65536];
    let mut idx = 0;
    let mut i = 0;
    while i < RLE_DATA.len() {
        let count = RLE_DATA[i] as usize;
        let val = RLE_DATA[i + 1];
        let end = (idx + count).min(65536);
        grid[idx..end].fill(val);
        idx = end;
        i += 2;
    }
    grid
}

/// The owl as BGRA pixels with straight alpha (as icons take them), `size` x `size`,
/// antialiased by 4 x 4 supersampling.
pub fn bgra(size: usize, white: bool) -> Vec<u8> {
    let mut out = vec![0u8; size * size * 4];
    if size == 0 {
        return out;
    }
    let grid = unpack_master();
    let scale = 256.0 / size as f32;
    for py in 0..size {
        for px in 0..size {
            let mut total_alpha = 0u32;
            let mut total_white = 0u32;
            for sy in 0..4 {
                for sx in 0..4 {
                    let x = (((px as f32 + (sx as f32 + 0.5) / 4.0) * scale) as usize).min(255);
                    let y = (((py as f32 + (sy as f32 + 0.5) / 4.0) * scale) as usize).min(255);
                    let val = grid[y * 256 + x];
                    if val == 1 {
                        total_alpha += 255;
                        total_white += 255;
                    } else if val == 2 {
                        total_alpha += 255;
                    }
                }
            }
            let alpha = (total_alpha / 16) as u8;
            let shade = (total_white * 255).checked_div(total_alpha).unwrap_or(0) as u8;
            let c = if white { shade } else { 255 - shade };
            out[(py * size + px) * 4..][..4].copy_from_slice(&[c, c, c, alpha]);
        }
    }
    out
}

